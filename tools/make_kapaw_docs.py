def page(title, h1, body):
    head_end = TEMPLATE.index('</head>')
    body_start = TEMPLATE.index('<section class="terms-page">')
    body_end = TEMPLATE.index('</section>', body_start) + len('</section>')
    # 하위 폴더라 머리글·바닥글의 사이트 경로를 한 칸 위로 (본문 안 카파우 문서끼리의 링크는 그대로)
    fix = lambda part: re.sub(r'(href|src)="(?!https?:|//|#|\.\./|mailto:|tel:)([^"]+)"', r'\1="../\2"', part)
    head = fix(TEMPLATE[:head_end])
    head = re.sub(r'<title>.*?</title>', f'<title>{title}</title>', head, flags=re.S)
    rest = fix(TEMPLATE[head_end:body_start]) + f'''<section class="terms-page">
        <div class="container">
            <a href="../index.html" class="back-link">
                <i class="fas fa-arrow-left"></i> 홈으로 돌아가기
            </a>

            <div class="terms-header">
                <h1>{h1}</h1>
                <p class="updated">카파우(KaPaw) · 시행일: {DATE}</p>
            </div>

            <div class="terms-content">
{body}
                {CONTACT}
            </div>
        </div>
    </section>''' + fix(TEMPLATE[body_end:])
    html = head + rest
    # 바닥글 바로가기에 카파우 문서 추가
    html = html.replace('<li><a href="../terms.html">이용약관</a></li>',
                        '<li><a href="../terms.html">이용약관</a></li>\n                        <li><a href="terms.html">카파우 이용약관</a></li>\n                        <li><a href="privacy.html">카파우 개인정보처리방침</a></li>\n                        <li><a href="delete.html">카파우 계정 삭제</a></li>', 1)
    return '<!-- 초안 (2026-10-05): 출시 전 법률 검토 권장. tools/make_kapaw_docs.py로 만듦 -->\n' + html


